def validate_component_results(component_results: pd.DataFrame, config: dict) -> None:
    """Validate that all required source scenarios and columns are present."""

    required_columns = [
        "target_date",
        "cutoff_timestamp",
        "horizon_days",
        "demand_type",
        "scenario_id",
        "forecast_value",
        "actual_value",
    ]

    missing_columns = [
        column
        for column in required_columns
        if column not in component_results.columns
    ]

    if missing_columns:
        raise RuntimeError(
            "Component results are missing required columns: "
            + ", ".join(missing_columns)
        )

    expected = set(
        config["required_entry_components"]
        + config["required_exit_components"]
    )

    found = set(component_results["scenario_id"].dropna().unique())
    missing_scenarios = sorted(expected - found)

    if missing_scenarios:
        raise RuntimeError(
            "Source simulation is missing required component scenarios: "
            + ", ".join(missing_scenarios)
        )

    duplicates = (
        component_results
        .duplicated(
            subset=[
                "target_date",
                "horizon_days",
                "demand_type",
                "scenario_id",
            ],
            keep=False,
        )
        .sum()
    )

    if duplicates:
        raise RuntimeError(
            f"Component results contain {duplicates:,} duplicate rows at "
            "target/horizon/flow/scenario grain."
        )


def regenerate_component_results(config: dict) -> pd.DataFrame:
    """
    Reload source data and regenerate only the scenarios required by FE/FX.

    This route reuses all source data loading, cleaning, cache building and
    scenario functions from fastpark_forecast_simulation.py.
    """

    base_config = base_sim.get_final_simulation_config()
    base_config["smoke_test"] = False
    base_config["fail_fast"] = True

    print("Loading and preparing source forecasting data...")

    raw_data = base_sim.load_simulation_data(base_config)
    base_sim.validate_loaded_data(raw_data, base_config)

    print("Loading multi-product bookings for pricing simulation...")

    pricing_bookings_raw = get_airportx_bookings_for_assets(
        start=base_config["history_start"],
        end=base_config["history_end"],
        statuses=["B", "CX", "F"],
        asset_names=config["price_analysis_assets"],
        engine=None,
    )

    pricing_bookings = clean_bookings(
        pricing_bookings_raw,
        base_config,
    )

    model_data = base_sim.prepare_forecast_model_data(
        data=raw_data,
        config=base_config,
    )

    test_dates = base_sim.create_test_dates(base_config)
    horizons = base_config["forecast_horizons_days"]

    entry_ids = config["required_entry_components"]
    exit_ids = config["required_exit_components"]

    all_rows = []
    total_snapshots = len(test_dates) * len(horizons)
    counter = 0

    print("\nGenerating required FE/FX source components...")

    for target_date in pd.to_datetime(test_dates["target_date"]).dt.normalize():
        for horizon_days in horizons:
            counter += 1

            print(
                f"\rComponents {counter:,}/{total_snapshots:,} "
                f"| Target {target_date.date()} | T-{horizon_days}",
                end="",
            )

            cutoff_timestamp = (
                target_date
                - pd.Timedelta(days=horizon_days)
                + pd.Timedelta(hours=7)
            )

            components = base_sim.build_snapshot_components(
                target_date=target_date,
                horizon_days=horizon_days,
                data=model_data,
            )

            model_data["current_snapshot_components"] = components

            for scenario_id in entry_ids:
                forecast, diagnostics = base_sim.forecast_entry_scenario(
                    scenario_id=scenario_id,
                    target_date=target_date,
                    cutoff_timestamp=cutoff_timestamp,
                    data=model_data,
                )

                all_rows.append(
                    {
                        "target_date": target_date,
                        "cutoff_timestamp": cutoff_timestamp,
                        "horizon_days": horizon_days,
                        "demand_type": "entry",
                        "scenario_id": scenario_id,
                        "forecast_value": forecast,
                        **diagnostics,
                    }
                )

            for scenario_id in exit_ids:
                forecast, diagnostics = base_sim.forecast_exit_scenario(
                    scenario_id=scenario_id,
                    target_date=target_date,
                    cutoff_timestamp=cutoff_timestamp,
                    data=model_data,
                )

                all_rows.append(
                    {
                        "target_date": target_date,
                        "cutoff_timestamp": cutoff_timestamp,
                        "horizon_days": horizon_days,
                        "demand_type": "exit",
                        "scenario_id": scenario_id,
                        "forecast_value": forecast,
                        **diagnostics,
                    }
                )

            model_data.pop("current_snapshot_components", None)

    print()

    component_results = pd.DataFrame(all_rows)

    actuals = model_data["daily_actuals"].copy()
    actuals["target_date"] = pd.to_datetime(
        actuals["date"],
        errors="coerce",
    ).dt.normalize()

    component_results = component_results.merge(
        actuals[["target_date", "entries", "exits"]],
        on="target_date",
        how="left",
    )

    component_results["actual_value"] = np.where(
        component_results["demand_type"].eq("entry"),
        component_results["entries"],
        component_results["exits"],
    )

    component_results = component_results.drop(
        columns=["entries", "exits"],
        errors="ignore",
    )

    validate_component_results(component_results, config)

    simulation_context = {
        "raw_data": raw_data,
        "model_data": model_data,
        "base_config": base_config,
        "test_dates": test_dates,
        "horizons": horizons,
        "pricing_bookings": pricing_bookings,
    }

    return component_results, simulation_context


def get_component_results(
    config: dict,
) -> tuple[pd.DataFrame, dict]:
    """Reload all source data and rerun the required component forecasts."""

    return regenerate_component_results(config)


