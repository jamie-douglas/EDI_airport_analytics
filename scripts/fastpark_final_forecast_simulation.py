def create_forecast_matrix(component_results: pd.DataFrame) -> pd.DataFrame:
    """Create one row per target date, cutoff, horizon and flow."""

    matrix = component_results.pivot_table(
        index=[
            "target_date",
            "cutoff_timestamp",
            "horizon_days",
            "demand_type",
            "actual_value",
        ],
        columns="scenario_id",
        values="forecast_value",
        aggfunc="first",
    ).reset_index()

    matrix.columns.name = None
    matrix["flow_type"] = np.where(
        matrix["demand_type"].eq("entry"),
        "ENTRY",
        "EXIT",
    )

    return matrix.sort_values(
        ["flow_type", "horizon_days", "target_date"]
    ).reset_index(drop=True)


