def run_final_scenario_tournament(
    component_results: pd.DataFrame,
    config: dict,
) -> pd.DataFrame:
    """Run FE1-FE4 and FX1-FX4."""

    matrix = create_forecast_matrix(component_results)
    three_weight_grid = create_three_component_weight_grid(config["weight_grid"])

    output_frames = []

    print("\nRunning final FE/FX expanding-window tournament...")

    for specification in config["two_component_scenarios"]:
        print(
            f"  Running {specification['scenario_id']} | "
            f"{specification['scenario_name']}"
        )

        output_frames.append(
            run_two_component_final_scenario(
                matrix=matrix,
                specification=specification,
                config=config,
            )
        )

    for specification in config["three_component_scenarios"]:
        print(
            f"  Running {specification['scenario_id']} | "
            f"{specification['scenario_name']}"
        )

        output_frames.append(
            run_three_component_final_scenario(
                matrix=matrix,
                specification=specification,
                config=config,
                weight_combinations=three_weight_grid,
            )
        )

    results = pd.concat(output_frames, ignore_index=True)

    results["error"] = results["forecast_value"] - results["actual_value"]
    results["absolute_error"] = results["error"].abs()
    results["squared_error"] = results["error"].pow(2)
    results["absolute_percentage_error"] = (
        results["absolute_error"]
        / results["actual_value"].abs().replace(0, np.nan)
    )
    results["weekday"] = results["target_date"].dt.day_name()
    results["weekday_num"] = results["target_date"].dt.weekday
    results["month"] = results["target_date"].dt.month
    results["year_month"] = results["target_date"].dt.to_period("M").astype(str)

    return results


