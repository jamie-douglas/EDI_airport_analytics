def print_final_summary(
    performance: pd.DataFrame,
    best_by_horizon: pd.DataFrame,
    weight_summary: pd.DataFrame,
) -> None:
    """Print the final FE/FX tournament summary."""

    print("\n" + "=" * 90)
    print("FASTPARK FINAL FE/FX SCENARIO RESULTS")
    print("=" * 90)

    print("\nBEST FINAL MODEL BY HORIZON")
    print("-" * 90)
    print(
        best_by_horizon[
            [
                "flow_type",
                "horizon_label",
                "scenario_id",
                "scenario_name",
                "wape_pct",
                "mae",
                "rmse",
                "bias",
                "coverage_pct",
            ]
        ].to_string(index=False)
    )

    print("\nOVERALL AVERAGE HORIZON RANK")
    print("-" * 90)

    overall = (
        performance
        .groupby(["flow_type", "scenario_id", "scenario_name"], as_index=False)
        .agg(
            average_wape_pct=("wape_pct", "mean"),
            average_mae=("mae", "mean"),
            average_bias=("bias", "mean"),
            average_rank=("wape_rank", "mean"),
            horizon_wins=("wape_rank", lambda values: int((values == 1).sum())),
        )
        .sort_values(["flow_type", "average_rank", "average_wape_pct"])
    )

    print(overall.to_string(index=False))

    print("\nWEIGHT-SELECTION COVERAGE")
    print("-" * 90)
    coverage = (
        weight_summary
        .groupby(["flow_type", "scenario_id"], as_index=False)
        .agg(
            expanding_selected_forecasts=("expanding_selected_forecasts", "sum"),
            fallback_forecasts=("fallback_forecasts", "sum"),
        )
    )
    print(coverage.to_string(index=False))


