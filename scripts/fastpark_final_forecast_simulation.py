def calculate_candidate_metrics(actual: pd.Series, forecast: pd.Series) -> dict:
    """Calculate the selection and reporting metrics for one candidate."""

    valid = actual.notna() & forecast.notna()
    actual_valid = actual.loc[valid].astype(float)
    forecast_valid = forecast.loc[valid].astype(float)

    if actual_valid.empty:
        return {
            "observations": 0,
            "wape_pct": np.nan,
            "mae": np.nan,
            "rmse": np.nan,
            "bias": np.nan,
        }

    error = forecast_valid - actual_valid
    denominator = actual_valid.abs().sum()

    return {
        "observations": int(len(actual_valid)),
        "wape_pct": (
            error.abs().sum() / denominator * 100
            if denominator > 0
            else np.nan
        ),
        "mae": float(error.abs().mean()),
        "rmse": float(np.sqrt(error.pow(2).mean())),
        "bias": float(error.mean()),
    }


def select_best_two_component_weight(
    training: pd.DataFrame,
    primary: str,
    comparison: str,
    weight_grid: list[float],
    minimum_observations: int,
    fallback_weight: float,
) -> dict:
    """Select the best two-component weight on historical training rows."""

    if len(training) < minimum_observations:
        return {
            "primary_weight": fallback_weight,
            "comparison_weight": 1.0 - fallback_weight,
            "training_observations": len(training),
            "training_wape_pct": np.nan,
            "training_mae": np.nan,
            "weight_source": "fallback_insufficient_history",
        }

    candidate_rows = []

    for primary_weight in weight_grid:
        forecast = weighted_forecast_two(
            training[primary],
            training[comparison],
            primary_weight,
        )

        metrics = calculate_candidate_metrics(
            training["actual_value"],
            forecast,
        )

        candidate_rows.append(
            {
                "primary_weight": primary_weight,
                "comparison_weight": 1.0 - primary_weight,
                **metrics,
            }
        )

    candidates = pd.DataFrame(candidate_rows)
    candidates = candidates[candidates["observations"] >= minimum_observations]

    if candidates.empty:
        return {
            "primary_weight": fallback_weight,
            "comparison_weight": 1.0 - fallback_weight,
            "training_observations": len(training),
            "training_wape_pct": np.nan,
            "training_mae": np.nan,
            "weight_source": "fallback_no_valid_candidate",
        }

    winner = candidates.sort_values(
        ["wape_pct", "mae", "primary_weight"],
        ascending=[True, True, False],
    ).iloc[0]

    return {
        "primary_weight": float(winner["primary_weight"]),
        "comparison_weight": float(winner["comparison_weight"]),
        "training_observations": int(winner["observations"]),
        "training_wape_pct": float(winner["wape_pct"]),
        "training_mae": float(winner["mae"]),
        "weight_source": "expanding_window_selected",
    }


def select_best_three_component_weights(
    training: pd.DataFrame,
    components: list[str],
    weight_combinations: list[tuple[float, float, float]],
    minimum_observations: int,
) -> dict:
    """Select the best three-component weights on historical training rows."""

    if len(training) < minimum_observations:
        return {
            "weight_1": 1.0,
            "weight_2": 0.0,
            "weight_3": 0.0,
            "training_observations": len(training),
            "training_wape_pct": np.nan,
            "training_mae": np.nan,
            "weight_source": "fallback_insufficient_history",
        }

    candidate_rows = []

    for weights in weight_combinations:
        forecast = weighted_forecast_three(
            training[components[0]],
            training[components[1]],
            training[components[2]],
            weights,
        )

        metrics = calculate_candidate_metrics(
            training["actual_value"],
            forecast,
        )

        candidate_rows.append(
            {
                "weight_1": weights[0],
                "weight_2": weights[1],
                "weight_3": weights[2],
                **metrics,
            }
        )

    candidates = pd.DataFrame(candidate_rows)
    candidates = candidates[candidates["observations"] >= minimum_observations]

    if candidates.empty:
        return {
            "weight_1": 1.0,
            "weight_2": 0.0,
            "weight_3": 0.0,
            "training_observations": len(training),
            "training_wape_pct": np.nan,
            "training_mae": np.nan,
            "weight_source": "fallback_no_valid_candidate",
        }

    winner = candidates.sort_values(
        ["wape_pct", "mae", "weight_1"],
        ascending=[True, True, False],
    ).iloc[0]

    return {
        "weight_1": float(winner["weight_1"]),
        "weight_2": float(winner["weight_2"]),
        "weight_3": float(winner["weight_3"]),
        "training_observations": int(winner["observations"]),
        "training_wape_pct": float(winner["wape_pct"]),
        "training_mae": float(winner["mae"]),
        "weight_source": "expanding_window_selected",
    }


