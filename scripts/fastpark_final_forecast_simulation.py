def create_three_component_weight_grid(weight_grid: Iterable[float]) -> list[tuple[float, float, float]]:
    """Return all non-negative three-component weights summing to one."""

    values = sorted(set(round(float(value), 10) for value in weight_grid))
    combinations = []

    for weight_1 in values:
        for weight_2 in values:
            weight_3 = round(1.0 - weight_1 - weight_2, 10)

            if weight_3 < 0:
                continue

            if weight_3 not in values:
                continue

            combinations.append((weight_1, weight_2, weight_3))

    return combinations


def weighted_forecast_two(
    primary: pd.Series,
    comparison: pd.Series,
    primary_weight: float,
) -> pd.Series:
    """Blend two forecasts, falling back to the available component."""

    comparison_weight = 1.0 - primary_weight

    output = (
        primary_weight * primary
        + comparison_weight * comparison
    )

    output = output.where(~primary.isna(), comparison)
    output = output.where(~comparison.isna(), primary)

    return output.clip(lower=0)


def weighted_forecast_three(
    component_1: pd.Series,
    component_2: pd.Series,
    component_3: pd.Series,
    weights: tuple[float, float, float],
) -> pd.Series:
    """Blend three forecasts and renormalise across available components."""

    frame = pd.DataFrame(
        {
            "c1": component_1,
            "c2": component_2,
            "c3": component_3,
        }
    )

    weight_array = np.array(weights, dtype=float)
    available = frame.notna().to_numpy(dtype=float)
    values = frame.fillna(0).to_numpy(dtype=float)

    effective_weights = available * weight_array
    denominator = effective_weights.sum(axis=1)
    numerator = (values * effective_weights).sum(axis=1)

    result = np.divide(
        numerator,
        denominator,
        out=np.full(len(frame), np.nan, dtype=float),
        where=denominator > 0,
    )

    return pd.Series(result, index=frame.index).clip(lower=0)


