def format_workbook(workbook) -> None:
    """Apply practical formatting to every sheet."""

    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter

    for worksheet in workbook.worksheets:
        worksheet.freeze_panes = "A2"

        if worksheet.max_row > 1:
            worksheet.auto_filter.ref = worksheet.dimensions

        for cell in worksheet[1]:
            cell.font = Font(bold=True)

        for column_cells in worksheet.columns:
            values = [
                len(str(cell.value))
                for cell in column_cells
                if cell.value is not None
            ]

            maximum_length = max(values) if values else 10
            column_letter = get_column_letter(column_cells[0].column)
            worksheet.column_dimensions[column_letter].width = min(
                max(maximum_length + 2, 10),
                60,
            )


def export_final_scenario_results(
    component_results: pd.DataFrame,
    final_results: pd.DataFrame,
    performance: pd.DataFrame,
    best_by_horizon: pd.DataFrame,
    weight_summary: pd.DataFrame,
    definitions: pd.DataFrame,
    pricing_snapshots: pd.DataFrame,
    pricing_duration_detail: pd.DataFrame,
    pricing_results: pd.DataFrame,
    pricing_performance: pd.DataFrame,
    output_path: Path,
) -> Path:
    """Export all FE/FX results to Excel."""

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    entry_performance = performance[performance["flow_type"].eq("ENTRY")]
    exit_performance = performance[performance["flow_type"].eq("EXIT")]

    entry_results = final_results[final_results["flow_type"].eq("ENTRY")]
    exit_results = final_results[final_results["flow_type"].eq("EXIT")]

    with pd.ExcelWriter(output_path, engine="openpyxl") as writer:
        best_by_horizon.to_excel(
            writer,
            sheet_name="Best Final By Horizon",
            index=False,
        )

        entry_performance.to_excel(
            writer,
            sheet_name="FE Performance",
            index=False,
        )

        exit_performance.to_excel(
            writer,
            sheet_name="FX Performance",
            index=False,
        )

        weight_summary.to_excel(
            writer,
            sheet_name="Weight Stability",
            index=False,
        )

        entry_results.to_excel(
            writer,
            sheet_name="FE Forecast Detail",
            index=False,
        )

        exit_results.to_excel(
            writer,
            sheet_name="FX Forecast Detail",
            index=False,
        )

        definitions.to_excel(
            writer,
            sheet_name="Final Scenario Definitions",
            index=False,
        )

        component_results.to_excel(
            writer,
            sheet_name="Source Components",
            index=False,
        )

        pricing_snapshots.to_excel(
            writer,
            sheet_name="Pricing Snapshot Detail",
            index=False,
        )

        pricing_duration_detail.to_excel(
            writer,
            sheet_name="Pricing by Duration",
            index=False,
        )

        pricing_results.to_excel(
            writer,
            sheet_name="PE Forecast Detail",
            index=False,
        )

        pricing_performance.to_excel(
            writer,
            sheet_name="Pricing vs FE Base",
            index=False,
        )

        format_workbook(writer.book)

    print(f"Exported FE/FX simulation workbook: {output_path}")
    return output_path


